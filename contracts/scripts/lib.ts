export type DeploymentJson = {
  chainId: number;
  network: string;
  usdc: string;
  ticket: string;
  booking: string;
  quoteSigner: string;
  deployer: string;
  deployBlock: number;
  deployedAt: string;
  operators: { address: string; name: string; kind: OperatorKind }[];
};

export function quoteSignerKey(): string {
  const k = process.env.QUOTE_SIGNER_PRIVATE_KEY?.trim();
  if (!k) return HARDHAT_SIGNER_KEY;
  return k.startsWith("0x") ? k : `0x${k}`;
}

export function deploymentPath(network: string) {
  return path.join(DEPLOYMENTS_DIR, `${network}.json`);
}

export function readDeployment(network: string): DeploymentJson {
  const p = deploymentPath(network);
  if (!fs.existsSync(p)) throw new Error(`No deployment for network "${network}" — run deploy first (${p})`);
  return JSON.parse(fs.readFileSync(p, "utf8"));
}

export function writeDeployment(d: DeploymentJson) {
  fs.mkdirSync(DEPLOYMENTS_DIR, { recursive: true });
  fs.writeFileSync(deploymentPath(d.network), JSON.stringify(d, null, 2) + "\n");
}

/** Regenerates web/src/lib/contracts.generated.ts from every deployments/*.json plus current ABIs. */
export async function writeGenerated(hre: HardhatRuntimeEnvironment) {
  const byChain: Record<number, DeploymentJson> = {};
  if (fs.existsSync(DEPLOYMENTS_DIR)) {
    for (const f of fs.readdirSync(DEPLOYMENTS_DIR).filter((x) => x.endsWith(".json")).sort()) {
      const d: DeploymentJson = JSON.parse(fs.readFileSync(path.join(DEPLOYMENTS_DIR, f), "utf8"));
      byChain[d.chainId] = d;
    }
  }

  const [booking, ticket, usdc] = await Promise.all([
    hre.artifacts.readArtifact("WayfareBooking"),
    hre.artifacts.readArtifact("WayfareTicket"),
    hre.artifacts.readArtifact("MockUSDC"),
  ]);

  const entries = Object.values(byChain)
    .sort((a, b) => a.chainId - b.chainId)
    .map((d) => {
      const obj = {
        chainId: d.chainId,
        usdc: d.usdc,
        ticket: d.ticket,
        booking: d.booking,
        quoteSigner: d.quoteSigner,
        deployBlock: d.deployBlock,
        deployedAt: d.deployedAt,
        operators: d.operators,
      };
      return `  ${d.chainId}: ${JSON.stringify(obj, null, 2).replace(/\n/g, "\n  ")},`;
    });

  const out = `// AUTO-GENERATED by contracts/scripts/deploy.ts — do not edit by hand.
// Regenerate with: npm run generate -w contracts

export type Address = \`0x\${string}\`;
export type OperatorKind = "flight" | "bus" | "train" | "boat" | "van";
export type Deployment = {
  chainId: number;
  usdc: Address;
  ticket: Address;
  booking: Address;
  quoteSigner: Address;
  deployBlock: number;
  deployedAt: string;
  operators: readonly { address: Address; name: string; kind: OperatorKind }[];
};

export const deployments = {
${entries.join("\n")}
} as const satisfies Record<number, Deployment>;

export const bookingAbi = ${JSON.stringify(booking.abi, null, 2)} as const;

export const ticketAbi = ${JSON.stringify(ticket.abi, null, 2)} as const;

export const usdcAbi = ${JSON.stringify(usdc.abi, null, 2)} as const;
`;
  fs.mkdirSync(path.dirname(GENERATED_FILE), { recursive: true });
  fs.writeFileSync(GENERATED_FILE, out);
  console.log(`Wrote ${GENERATED_FILE} (chains: ${Object.keys(byChain).join(", ") || "none"})`);
}
